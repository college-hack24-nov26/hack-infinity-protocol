def valid_email(email):

    return bool(
        re.fullmatch(
            r"[^@\s]+@[^@\s]+\.[^@\s]+",
            email
        )
    )


# --------------------------------------------------
# JWT TOKEN
# --------------------------------------------------

def create_token(user_id):

    secret_key = app.config.get("SECRET_KEY")

    if not secret_key:
        raise RuntimeError(
            "MEDIFIND_SECRET_KEY is missing in backend/.env"
        )

    payload = {
        "user_id": user_id,
        "exp": datetime.now(timezone.utc) + timedelta(days=1)
    }

    return jwt.encode(
        payload,
        secret_key,
        algorithm="HS256"
    )


