@app.route("/api/medicines/search", methods=["GET"])
def search_medicines():

    conn = None

    try:
        medicine_name = request.args.get("name", "").strip()

        if not medicine_name:
            return jsonify({
                "status": "error",
                "message": "Please enter a medicine name."
            }), 400

        conn = get_db()

        with conn.cursor() as cur:

            cur.execute("""
                SELECT
                    ms.id,
                    ms.medicine_name,
                    ms.quantity,
                    ms.price,
                    p.pharmacy_name,
                    p.location,
                    p.phone
                FROM medicine_stock ms
                JOIN pharmacies p
                    ON ms.pharmacy_id = p.id
                WHERE LOWER(ms.medicine_name)
                    LIKE LOWER(%s)
                    AND ms.quantity > 0
                ORDER BY ms.medicine_name
            """, (f"%{medicine_name}%",))

            medicines = cur.fetchall()

        return jsonify({
            "status": "success",
            "count": len(medicines),
            "medicines": medicines
        })

    except Exception:

        logger.exception("Medicine search failed")

        return jsonify({
            "status": "error",
            "message": "Medicine search failed."
        }), 500

    finally:
        if conn:
            conn.close()


